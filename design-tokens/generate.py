#!/usr/bin/env python3
"""Generates platform token files from tokens.json (standard library only).

    python3 design-tokens/generate.py

Writes ios/KametiKit/Sources/KametiUI/Generated/Tokens.generated.swift.
Add a Kotlin writer here when the Android app starts, so both apps read the
same source of truth.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SWIFT_OUT = HERE.parent / "ios/KametiKit/Sources/KametiUI/Generated/Tokens.generated.swift"
tokens = json.loads((HERE / "tokens.json").read_text())


def hex_int(value):
    return int((value["hex"] if isinstance(value, dict) else value).lstrip("#"), 16)


def alpha(value):
    return value["alpha"] if isinstance(value, dict) else 1.0


def swift_color(light, dark):
    return f"KDynamicColor(light: 0x{hex_int(light):06X}, lightAlpha: {alpha(light)}, dark: 0x{hex_int(dark):06X}, darkAlpha: {alpha(dark)})"


def num(value):
    return f"{value}" if isinstance(value, int) else repr(value)


out = [
    "// Generated by design-tokens/generate.py from tokens.json. Do not edit by hand.",
    "import SwiftUI",
    "",
    "/// Semantic colour tokens (direction A, Ledger). Each adapts to light and dark mode.",
    "public enum KColors {",
]
light, dark = tokens["colors"]["light"], tokens["colors"]["dark"]
for name in light:
    out.append(f"    public static let {name} = {swift_color(light[name], dark[name])}.color")
out += ["", "    /// Member palette, 8 entries. Prefer `avatar(_:)`, which wraps any index.",
        "    public static let avatars: [(background: Color, foreground: Color)] = ["]
for a_light, a_dark in zip(tokens["colors"]["avatars"]["light"], tokens["colors"]["avatars"]["dark"]):
    out.append(
        f"        ({swift_color(a_light['background'], a_dark['background'])}.color, "
        f"{swift_color(a_light['foreground'], a_dark['foreground'])}.color),"
    )
out += ["    ]", "}", "", "/// Spacing scale.", "public enum KSpace {"]
for name, value in tokens["space"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Corner radii.", "public enum KRadius {"]
for name, value in tokens["radius"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Minimum interactive and component sizes.", "public enum KSize {"]
for name, value in tokens["size"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Text styles. Sizes are the base size at the default Dynamic Type setting.",
        "public enum KTextToken {"]
weights = {"regular": ".regular", "semibold": ".semibold", "bold": ".bold"}
for name, t in tokens["typography"].items():
    out.append(
        f"    public static let {name} = KTextStyle(size: {num(t['size'])}, weight: {weights[t['weight']]}, "
        f"tracking: {num(t['tracking'])}, tabular: {'true' if t['tabular'] else 'false'})"
    )
out += ["}", ""]
SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
SWIFT_OUT.write_text("\n".join(out))
print(f"wrote {SWIFT_OUT.relative_to(HERE.parent.parent)}")
