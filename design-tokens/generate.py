#!/usr/bin/env python3
"""Generates platform token files from tokens.json (standard library only).

    python3 design-tokens/generate.py

Writes:
  ios/KametiKit/Sources/KametiUI/Generated/Tokens.generated.swift
  android/ui/src/main/kotlin/com/brixel/kameti/ui/generated/Tokens.generated.kt

Both apps read the same source of truth.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SWIFT_OUT = HERE.parent / "ios/KametiKit/Sources/KametiUI/Generated/Tokens.generated.swift"
KOTLIN_OUT = HERE.parent / "android/ui/src/main/kotlin/com/brixel/kameti/ui/generated/Tokens.generated.kt"
tokens = json.loads((HERE / "tokens.json").read_text())


def hex_int(value):
    return int((value["hex"] if isinstance(value, dict) else value).lstrip("#"), 16)


def alpha(value):
    return value["alpha"] if isinstance(value, dict) else 1.0


def swift_color(light, dark):
    return f"KDynamicColor(light: 0x{hex_int(light):06X}, lightAlpha: {alpha(light)}, dark: 0x{hex_int(dark):06X}, darkAlpha: {alpha(dark)})"


def num(value):
    return f"{value}" if isinstance(value, int) else repr(value)


out = [
    "// Generated by design-tokens/generate.py from tokens.json. Do not edit by hand.",
    "import SwiftUI",
    "",
    "/// Semantic colour tokens (direction A, Ledger). Each adapts to light and dark mode.",
    "public enum KColors {",
]
light, dark = tokens["colors"]["light"], tokens["colors"]["dark"]
for name in light:
    out.append(f"    public static let {name} = {swift_color(light[name], dark[name])}.color")
out += ["", "    /// Member palette, 8 entries. Prefer `avatar(_:)`, which wraps any index.",
        "    public static let avatars: [(background: Color, foreground: Color)] = ["]
for a_light, a_dark in zip(tokens["colors"]["avatars"]["light"], tokens["colors"]["avatars"]["dark"]):
    out.append(
        f"        ({swift_color(a_light['background'], a_dark['background'])}.color, "
        f"{swift_color(a_light['foreground'], a_dark['foreground'])}.color),"
    )
out += ["    ]", "}", "", "/// Spacing scale.", "public enum KSpace {"]
for name, value in tokens["space"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Corner radii.", "public enum KRadius {"]
for name, value in tokens["radius"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Minimum interactive and component sizes.", "public enum KSize {"]
for name, value in tokens["size"].items():
    out.append(f"    public static let {name}: CGFloat = {num(value)}")
out += ["}", "", "/// Text styles. Sizes are the base size at the default Dynamic Type setting.",
        "public enum KTextToken {"]
weights = {"regular": ".regular", "semibold": ".semibold", "bold": ".bold"}
for name, t in tokens["typography"].items():
    out.append(
        f"    public static let {name} = KTextStyle(size: {num(t['size'])}, weight: {weights[t['weight']]}, "
        f"tracking: {num(t['tracking'])}, tabular: {'true' if t['tabular'] else 'false'})"
    )
out += ["}", ""]
SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
SWIFT_OUT.write_text("\n".join(out))
print(f"wrote {SWIFT_OUT.relative_to(HERE.parent.parent)}")


# ---------------------------------------------------------------- Kotlin ----

def kotlin_color(value):
    argb = (round(alpha(value) * 255) << 24) | hex_int(value)
    return f"Color(0x{argb:08X})"


def kotlin_float(value):
    return f"{float(value)}f"


def kotlin_scheme(name, colors, avatars):
    lines = [f"val {name} = KColorScheme("]
    for key, value in colors.items():
        lines.append(f"    {key} = {kotlin_color(value)},")
    lines.append("    avatars = listOf(")
    for a in avatars:
        lines.append(f"        KAvatarColors({kotlin_color(a['background'])}, {kotlin_color(a['foreground'])}),")
    lines += ["    ),", ")", ""]
    return lines


kt = [
    "// Generated by design-tokens/generate.py from tokens.json. Do not edit by hand.",
    "package com.brixel.kameti.ui",
    "",
    "import androidx.compose.runtime.Composable",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.runtime.ReadOnlyComposable",
    "import androidx.compose.runtime.staticCompositionLocalOf",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.dp",
    "",
    "/** One member-palette entry. */",
    "@Immutable",
    "data class KAvatarColors(val background: Color, val foreground: Color)",
    "",
    "/** Every semantic colour for one appearance (light or dark). */",
    "@Immutable",
    "data class KColorScheme(",
]
for name in light:
    kt.append(f"    val {name}: Color,")
kt += ["    val avatars: List<KAvatarColors>,", ")", ""]
kt += kotlin_scheme("KLightColors", light, tokens["colors"]["avatars"]["light"])
kt += kotlin_scheme("KDarkColors", dark, tokens["colors"]["avatars"]["dark"])
kt += [
    "/** Set by `KTheme`; read through [KColors]. */",
    "val LocalKColors = staticCompositionLocalOf { KLightColors }",
    "",
    "/** Semantic colour tokens (direction A, Ledger). Each adapts to light and dark mode. */",
    "object KColors {",
]
for name in light:
    kt.append(f"    val {name}: Color @Composable @ReadOnlyComposable get() = LocalKColors.current.{name}")
kt += [
    "",
    "    /** Member palette, 8 entries; wraps any index. */",
    "    @Composable",
    "    @ReadOnlyComposable",
    "    fun avatar(index: Int): KAvatarColors = LocalKColors.current.avatars.let { it[Math.floorMod(index, it.size)] }",
    "}",
    "",
    "/** Spacing scale. */",
    "object KSpace {",
]
for name, value in tokens["space"].items():
    kt.append(f"    val {name} = {num(value)}.dp")
kt += ["}", "", "/** Corner radii. */", "object KRadius {"]
for name, value in tokens["radius"].items():
    kt.append(f"    val {name} = {num(value)}.dp")
kt += ["}", "", "/** Minimum interactive and component sizes. */", "object KSize {"]
for name, value in tokens["size"].items():
    kt.append(f"    val {name} = {num(value)}.dp")
kt += ["}", "", "/** Text styles. Sizes are in sp, so they scale with the user's font size. */", "object KTextToken {"]
kotlin_weights = {"regular": "FontWeight.Normal", "semibold": "FontWeight.SemiBold", "bold": "FontWeight.Bold"}
for name, t in tokens["typography"].items():
    kt.append(
        f"    val {name} = KTextStyle(size = {kotlin_float(t['size'])}, weight = {kotlin_weights[t['weight']]}, "
        f"tracking = {kotlin_float(t['tracking'])}, tabular = {'true' if t['tabular'] else 'false'})"
    )
kt += ["}", ""]
KOTLIN_OUT.parent.mkdir(parents=True, exist_ok=True)
KOTLIN_OUT.write_text("\n".join(kt))
print(f"wrote {KOTLIN_OUT.relative_to(HERE.parent)}")
