#!/usr/bin/env python3
"""Turns the iOS String Catalogs into Android strings.xml (standard library only).

    python3 android/scripts/import-strings.py            # rewrite every strings.xml
    python3 android/scripts/import-strings.py --find "Try again"   # look up a name

The iOS catalogs (ios/KametiKit/Sources/<Target>/Resources/Localizable.xcstrings)
are the source of the wording, so both apps always say the same thing. Each
catalog becomes `<module>/src/main/res/values/strings.xml`. Do not edit those
files by hand: change the catalog and run this again.

Catalog keys are English sentences, so each resource name is the module's
prefix plus the sentence in snake_case:

    "Couldn't load your kametis"  ->  home_couldnt_load_your_kametis
    "%lld of %lld paid"           ->  home_n_of_n_paid      (%1$d of %2$d paid)

Swift placeholders become Android ones: %@ -> %s, %lld -> %d, numbered when a
string has more than one.
"""
import json
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOGS = ROOT / "ios/KametiKit/Sources"
ANDROID = ROOT / "android"

# Swift target -> (Gradle module directory, resource name prefix)
MODULES = {
    "KametiUI": ("ui", "ui"),
    "FeatureAuth": ("feature/auth", "auth"),
    "FeatureHome": ("feature/home", "home"),
    "FeatureKametiDetail": ("feature/kametidetail", "detail"),
    "FeatureCreateKameti": ("feature/createkameti", "create"),
    "FeatureInvites": ("feature/invites", "invites"),
    "FeatureShell": ("feature/shell", "shell"),
}

PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|d|lf|f)")
MAX_WORDS = 8


def resource_name(prefix, key):
    """The module prefix plus the sentence in snake_case, at most MAX_WORDS words."""
    text = PLACEHOLDER.sub(lambda m: " n " if m.group(2) in ("lld", "ld", "d") else " s ", key)
    text = text.replace("%%", " percent ").replace("'", "").replace("\u2019", "")
    words = re.findall(r"[a-z0-9]+", text.lower())
    return "_".join([prefix] + (words[:MAX_WORDS] or ["text"]))


def android_value(value):
    """Swift format string -> Android string resource text."""
    count = len(PLACEHOLDER.findall(value))
    position = 0

    def convert(match):
        nonlocal position
        position += 1
        kind = "s" if match.group(2) == "@" else ("f" if match.group(2) in ("lf", "f") else "d")
        if match.group(1):
            return f"%{match.group(1)}${kind}"
        return f"%{position}${kind}" if count > 1 else f"%{kind}"

    text = PLACEHOLDER.sub(convert, value)
    if count == 0:
        # Not a format string on Android: a literal percent is a single character.
        text = text.replace("%%", "%")
    text = text.replace("\\", "\\\\")
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    if text != text.strip() or "  " in text:
        text = f'"{text}"'  # keep leading, trailing and double spaces
    return text, count > 0


def entries(target):
    """[(name, key, value)] for one catalog, names unique and stable."""
    _, prefix = MODULES[target]
    catalog = json.loads((CATALOGS / target / "Resources/Localizable.xcstrings").read_text())
    rows, by_name = [], {}
    for key in sorted(catalog["strings"]):
        entry = catalog["strings"][key]
        unit = entry.get("localizations", {}).get("en", {}).get("stringUnit")
        value = unit["value"] if unit else key
        name = resource_name(prefix, key)
        by_name.setdefault(name, []).append((key, value))
    for name, group in by_name.items():
        if len(group) == 1:
            rows.append((name, *group[0]))
            continue
        # Two sentences shorten to the same name: tell them apart by a short
        # checksum of the sentence, which doesn't change when others are added.
        for key, value in group:
            rows.append((f"{name}_{zlib.crc32(key.encode()) & 0xFFFF:04x}", key, value))
    return sorted(rows)


def write(target):
    module, _ = MODULES[target]
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by android/scripts/import-strings.py from {target}'s String Catalog. Do not edit by hand. -->",
        "<resources>",
    ]
    for name, _, value in entries(target):
        text, formatted = android_value(value)
        attribute = "" if formatted or "%" not in text else ' formatted="false"'
        lines.append(f'    <string name="{name}"{attribute}>{text}</string>')
    lines += ["</resources>", ""]
    out = ANDROID / module / "src/main/res/values/strings.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)} ({len(lines) - 4} strings)")


def find(needle):
    needle = needle.lower()
    for target in MODULES:
        for name, key, value in entries(target):
            if needle in key.lower() or needle in value.lower():
                print(f"{MODULES[target][0]}: R.string.{name}  <-  {key!r}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--find":
        find(sys.argv[2])
    elif len(sys.argv) == 1:
        for target in MODULES:
            write(target)
    else:
        sys.exit(__doc__)
